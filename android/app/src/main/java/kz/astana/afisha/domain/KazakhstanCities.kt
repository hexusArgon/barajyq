package kz.astana.afisha.domain

/** [name] is Russian; Kazakh and Latin (English) names are derived via [KazakhstanCities]. */
data class City(val id: String, val name: String) {
    /** Latin name (English UI). */
    val latinName: String
        get() = KazakhstanCities.enOverrides[id]
            ?: id.split('-').joinToString("-") { part -> part.replaceFirstChar { it.uppercase() } }

    /** Kazakh (Cyrillic) name. */
    val kkName: String get() = KazakhstanCities.kkNames[id] ?: name

    fun displayName(lang: AppLanguage?): String = pick(lang, kkName, name, latinName)

    fun matches(query: String): Boolean {
        val q = query.trim()
        return q.isEmpty() || name.contains(q, ignoreCase = true) || latinName.contains(q, ignoreCase = true) ||
            kkName.contains(q, ignoreCase = true)
    }
}

