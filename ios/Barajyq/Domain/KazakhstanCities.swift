import Foundation

/// `name` is Russian; Kazakh and Latin (English) names via `KazakhstanCities`. Порт `domain/KazakhstanCities.kt`.
struct City: Identifiable, Hashable {
    let id: String
    let name: String

    /// Latin name (English UI).
    var latinName: String {
        KazakhstanCities.enOverrides[id] ?? id.split(separator: "-").map { $0.prefix(1).uppercased() + $0.dropFirst() }.joined(separator: "-")
    }

    /// Kazakh (Cyrillic) name.
    var kkName: String { KazakhstanCities.kkNames[id] ?? name }

    func displayName(_ lang: AppLanguage?) -> String { pick(lang, kk: kkName, ru: name, en: latinName) }

    func matches(_ query: String) -> Bool {
        let q = query.trimmingCharacters(in: .whitespaces)
        if q.isEmpty { return true }
        return [name, latinName, kkName].contains { $0.range(of: q, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
    }
}

