#!/usr/bin/env python3
"""Generates the real-data blocks of FakeEventsRepository / FakePlacesRepository (Android .kt + iOS .swift)
and the D section of descriptions_data.py from tools/feed_data.json (scraped sxodim.com, astanaopera.kz,
nmrk.kz, ru.wikipedia.org; kk/en from the sites' own language versions or translated).
Run from repo root: python3 tools/gen_feed.py && python3 tools/gen_descriptions.py"""
import json, pathlib, re
from event_policy import keep_canonical
ROOT = pathlib.Path(__file__).resolve().parent.parent
F = [x for x in json.loads((ROOT / 'tools/feed_data.json').read_text()) if keep_canonical(x)]
KT = ROOT / 'android/app/src/main/java/kz/astana/afisha/data'
SW = ROOT / 'ios/Barajyq/Data'
B, E = '// BEGIN GENERATED by tools/gen_feed.py', '// END GENERATED'

def kq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', ' ') + '"'
def sq(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
def kopt(v, q=kq): return 'null' if v is None else (q(v) if isinstance(v, str) else repr(float(v)))
def sopt(v): return 'nil' if v is None else (sq(v) if isinstance(v, str) else repr(float(v)))

KT_HELPER = '''    private fun real(
        id: String, city: String, interest: Interest, isPlace: Boolean,
        tRu: String, tKk: String, tEn: String, startsAt: String,
        pRu: String, pKk: String, pEn: String, address: String, price: String?,
        url: String, source: String, hours: String, lat: Double?, lon: Double?,
    ): EventCard {
        val d = Descriptions.forId(id)
        return EventCard(
            id = id, cityId = city, titleRu = tRu, titleKk = tKk, titleEn = tEn, startsAt = startsAt,
            placeRu = pRu, placeKk = pKk, placeEn = pEn, address = address, interest = interest, price = price,
            whyMatches = "Интерес: ${interest.labelRu.lowercase()}", sourceUrl = url, sourceName = source,
            isPlace = isPlace, workingHours = hours,
            descriptionRu = d?.ru.orEmpty(), descriptionKk = d?.kk.orEmpty(), descriptionEn = d?.en.orEmpty(),
            lat = lat, lon = lon,
        )
    }
'''
SW_HELPER = '''    private static func real(
        _ id: String, _ city: String, _ interest: Interest, _ isPlace: Bool,
        _ tRu: String, _ tKk: String, _ tEn: String, _ startsAt: String,
        _ pRu: String, _ pKk: String, _ pEn: String, _ address: String, _ price: String?,
        _ url: String, _ source: String, _ hours: String, _ lat: Double?, _ lon: Double?
    ) -> EventCard {
        let d = Descriptions.forId(id)
        return EventCard(
            id: id, cityId: city, titleRu: tRu, titleKk: tKk, titleEn: tEn, startsAt: startsAt,
            placeRu: pRu, placeKk: pKk, placeEn: pEn, address: address, interest: interest, price: price,
            whyMatches: "Интерес: \\(interest.labelRu.lowercased())", sourceUrl: url, sourceName: source,
            isPlace: isPlace, workingHours: hours,
            descriptionRu: d?.ru ?? "", descriptionKk: d?.kk ?? "", descriptionEn: d?.en ?? "",
            lat: lat, lon: lon
        )
    }
'''

def kt_call(x):
    a = [kq(x['id']), kq(x['city']), 'Interest.' + x['interest'], 'false' if x['ev'] else 'true',
         *map(kq, x['t']), kq(x['st']), *map(kq, x['p']), kq(x['addr']), kopt(x['price']),
         kq(x['url']), kq(x['src']), kq(x['hours']), kopt(x['lat']), kopt(x['lon'])]
    return '        real(' + ', '.join(a) + '),'
def sw_call(x):
    a = [sq(x['id']), sq(x['city']), '.' + x['interest'].lower(), 'false' if x['ev'] else 'true',
         *map(sq, x['t']), sq(x['st']), *map(sq, x['p']), sq(x['addr']), sopt(x['price']),
         sq(x['url']), sq(x['src']), sq(x['hours']), sopt(x['lat']), sopt(x['lon'])]
    return '        real(' + ', '.join(a) + '),'

def block(ev, swift):
    out = [B, SW_HELPER if swift else KT_HELPER]
    for c in ('astana', 'almaty', 'shymkent'):
        xs = [x for x in F if x['city'] == c and x['ev'] == ev]
        out.append(f'    private static let {c}: [EventCard] = [' if swift else f'    private val {c}: List<EventCard> = listOf(')
        out += [(sw_call if swift else kt_call)(x) for x in xs]
        out.append('    ]' if swift else '    )')
        out.append('')
    out.append('    ' + E)
    return '\n'.join(out) + '\n'

def patch(path, ev, swift):
    s = path.read_text()
    if B in s:
        i = s.index(B); j = s.index(E) + len(E) + 1
        s = s[:i] + block(ev, swift).lstrip() + s[j:] if False else s[:i] + block(ev, swift) + s[j:]
    else:
        start = re.search(r'    private (static let|val) astana', s).start()
        end = re.search(r'    private (static var|val) cache', s).start()
        s = s[:start] + '    ' + block(ev, swift) + '\n' + s[end:]
    path.write_text(s)

patch(KT / 'FakeEventsRepository.kt', True, False)
patch(KT / 'FakePlacesRepository.kt', False, False)
patch(SW / 'FakeEventsRepository.swift', True, True)
patch(SW / 'FakePlacesRepository.swift', False, True)

# descriptions_data.py: rewrite the D section (keep header + templates)
dp = ROOT / 'tools/descriptions_data.py'
s = dp.read_text()
head = '# Single source of truth for in-app descriptions (ru, kk, en). Generates Kotlin + Swift.\n' \
       '# The D section is GENERATED by tools/gen_feed.py from tools/feed_data.json (full texts from the source pages).\nD = {}\ndef d(i, ru, kk, en): D[i] = (ru, kk, en)\n\n'
tail = s[s.index('# ---------------- Templates'):]
body = ''.join(f'd({x["id"]!r},\n {x["d"][0]!r},\n {x["d"][1]!r},\n {x["d"][2]!r})\n' for x in F)
dp.write_text(head + body + '\n' + tail)
print('ok', len(F))
