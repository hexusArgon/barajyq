#!/usr/bin/env python3
"""Generates Android Descriptions.kt and iOS Descriptions.swift from descriptions_data.py.
Run from repo root: python3 tools/gen_descriptions.py"""
import pathlib, sys
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
from descriptions_data import D, T_EV, T_PL

def kq(s):  # Kotlin string literal
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\r', '').replace('\n', '\\n').replace('\t', ' ') + '"'
def sq(s):  # Swift string literal
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\r', '').replace('\n', '\\n').replace('\t', ' ') + '"'

def ktpl(s):
    return kq(s).replace('{n}', '${n}').replace('{k}', '${k}').replace('{e}', '${e}')
def swtpl(s):
    return sq(s).replace('{n}', '\\(n)').replace('{k}', '\\(k)').replace('{e}', '\\(e)')

HDR = "GENERATED by tools/gen_descriptions.py from tools/descriptions_data.py — edit the data file, not this one."

kt = [f"// {HDR}", "package kz.astana.afisha.data", "",
      "/** Full in-app descriptions (ru, kk, en) keyed by EventCard.id. */",
      "object Descriptions {",
      "    data class Text(val ru: String, val kk: String, val en: String)", "",
      "    private val map: Map<String, Text> = mapOf("]
for k, (r, kk_, e) in D.items():
    kt.append(f"        {kq(k)} to Text(\n            {kq(r)},\n            {kq(kk_)},\n            {kq(e)},\n        ),")
kt += ["    )", "", "    fun forId(id: String): Text? = map[id]", ""]
for name, T in (("event", T_EV), ("place", T_PL)):
    kt.append(f"    /** Template for generated cities: n = ru, k = kk, e = en city name. */")
    kt.append(f"    fun {name}Template(num: Int, n: String, k: String, e: String): Text = when (num) {{")
    for i, (r, kk_, e) in T.items():
        kt.append(f"        {i} -> Text(\n            {ktpl(r)},\n            {ktpl(kk_)},\n            {ktpl(e)},\n        )")
    kt.append("        else -> Text(\"\", \"\", \"\")")
    kt.append("    }")
kt += ["}", ""]
(ROOT / 'android/app/src/main/java/kz/astana/afisha/data/Descriptions.kt').write_text("\n".join(kt))

sw = [f"// {HDR}", "import Foundation", "",
      "/// Full in-app descriptions (ru, kk, en) keyed by EventCard.id (порт Android `data/Descriptions.kt`).",
      "enum Descriptions {",
      "    struct Text { let ru: String; let kk: String; let en: String }", "",
      "    private static let map: [String: Text] = ["]
for k, (r, kk_, e) in D.items():
    sw.append(f"        {sq(k)}: Text(\n            ru: {sq(r)},\n            kk: {sq(kk_)},\n            en: {sq(e)}\n        ),")
sw += ["    ]", "", "    static func forId(_ id: String) -> Text? { map[id] }", ""]
for name, T in (("event", T_EV), ("place", T_PL)):
    sw.append(f"    /// Template for generated cities: n = ru, k = kk, e = en city name.")
    sw.append(f"    static func {name}Template(_ num: Int, n: String, k: String, e: String) -> Text {{")
    sw.append("        switch num {")
    for i, (r, kk_, e) in T.items():
        sw.append(f"        case {i}: return Text(\n            ru: {swtpl(r)},\n            kk: {swtpl(kk_)},\n            en: {swtpl(e)}\n        )")
    sw.append("        default: return Text(ru: \"\", kk: \"\", en: \"\")")
    sw.append("        }")
    sw.append("    }")
sw += ["}", ""]
(ROOT / 'ios/Barajyq/Data/Descriptions.swift').write_text("\n".join(sw))
print("ok", len(D))
